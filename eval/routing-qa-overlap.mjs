#!/usr/bin/env node
/**
 * Writes eval/routing-qa-overlap.json: the routing and discovery rows whose question matches a QA
 * headline question (eval/qa/cases.json), per question set. The lists hold routing row ids only,
 * no QA id and no score. Runners tag those rows confirmation-only (eval/README.md).
 *
 * A match is a token Jaccard of at least 0.8 against any QA question: lowercase, NFKC,
 * `[\p{L}\p{N}]+` token sets, and the integer test 5 * |A ∩ B| >= 4 * |A ∪ B|.
 *
 * Usage: node eval/routing-qa-overlap.mjs [--check]
 * `--check` recomputes and exits 1 when the committed file differs (npm test runs the same check).
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeFileAtomic } from "../scripts/lib/shared.mjs";

const EVAL_DIR = dirname(fileURLToPath(import.meta.url));
export const OVERLAP_PATH = join(EVAL_DIR, "routing-qa-overlap.json");
export const REGENERATE_COMMAND = "npm run eval:routing:overlap";

const readJson = (root, rel) => JSON.parse(readFileSync(join(root, rel), "utf8"));

export function tokenSet(text) {
  return new Set(String(text).normalize("NFKC").toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? []);
}

/** Jaccard >= 0.8 on two token sets, by integers. Two empty sets never match. */
export function matchesAtThreshold(a, b) {
  if (a.size === 0 || b.size === 0) return false;
  let intersection = 0;
  for (const token of a) if (b.has(token)) intersection += 1;
  const union = a.size + b.size - intersection;
  return 5 * intersection >= 4 * union;
}

const pick = (rows, field = "question") => rows.map((row) => ({ id: row.id, question: row[field] }));

/**
 * Every committed routing and discovery question set. A new routing or discovery question set is
 * added here, and `set` is the name its runner passes to eval/lib/confirmation-only.mjs.
 */
export const QUESTION_SETS = [
  { set: "legacy", file: "eval/routing-cases.json", rows: (j) => pick(j.cases) },
  { set: "extended", file: "eval/routing-cases.json", rows: (j) => pick(j.extendedCases) },
  { set: "skills", file: "eval/skills-cases.json", rows: (j) => pick(j.cases) },
  { set: "holdout", file: "eval/holdout-cases.json", rows: (j) => pick(j.cases) },
  { set: "discovery", file: "eval/discovery/cases.json", rows: (j) => pick(j.cases) },
  { set: "mined-replay", file: "eval/discovery/mined-lumenloop-queries.json", rows: (j) => pick(j.occurrences, "query") },
  { set: "agentic", file: "eval/agentic/sample.json", rows: (j) => pick(j.cases) },
  {
    set: "protocol-history-v1",
    file: "eval/protocol-history-cases.json",
    rows: (j) => pick([...j.positiveCases, ...j.controlCases]),
  },
  {
    set: "protocol-history-v2",
    file: "eval/protocol-history-cases-v2.json",
    rows: (j) => pick([...j.requiredCases, ...j.forbiddenCases, ...j.neutralCases]),
  },
  {
    set: "protocol-history-blind-v1",
    file: "eval/protocol-history-blind-cases.json",
    rows: (j) => pick([...j.positiveCases, ...j.controlCases]),
  },
  {
    set: "protocol-history-blind-v2",
    file: "eval/protocol-history-blind-cases-v2.json",
    rows: (j) => pick([...j.requiredCases, ...j.forbiddenCases, ...j.neutralCases]),
  },
];

/** The list object for the repository at `root`. No timestamp, so the whole file can be compared. */
export function computeOverlap(root = resolve(EVAL_DIR, "..")) {
  const qaTokens = readJson(root, "eval/qa/cases.json").cases.map((c) => tokenSet(c.question));
  const sets = {};
  for (const { set, file, rows } of QUESTION_SETS) {
    const questions = rows(readJson(root, file));
    const seen = new Set();
    const ids = [];
    for (const { id, question } of questions) {
      if (seen.has(id)) throw new Error(`set "${set}" repeats row id "${id}"`);
      seen.add(id);
      const tokens = tokenSet(question);
      if (qaTokens.some((qa) => matchesAtThreshold(tokens, qa))) ids.push(id);
    }
    sets[set] = { source: file, total: questions.length, listed: ids.length, ids: ids.sort() };
  }
  return {
    $comment:
      "Generated by eval/routing-qa-overlap.mjs; do not edit by hand. Routing and discovery rows whose question matches a QA headline question are confirmation-only: aggregate counts only, never per-row output, never tuned on. The lists hold routing row ids only.",
    rule: {
      against: "every question in eval/qa/cases.json",
      tokenizer: "NFKC, lowercase, token set of [\\p{L}\\p{N}]+",
      match: "5 * |A ∩ B| >= 4 * |A ∪ B| (token Jaccard >= 0.8)",
    },
    sets,
  };
}

export const serialize = (overlap) => `${JSON.stringify(overlap, null, 2)}\n`;

/** The per-set differences between a committed and a recomputed list, as counts only. */
export function overlapDifferences(committed, computed) {
  const names = new Set([...Object.keys(committed?.sets ?? {}), ...Object.keys(computed.sets)]);
  const lines = [];
  for (const name of [...names].sort()) {
    const had = committed?.sets?.[name]?.ids.length;
    const now = computed.sets[name]?.ids.length;
    if (JSON.stringify(committed?.sets?.[name]) !== JSON.stringify(computed.sets[name])) {
      lines.push(`set "${name}": committed lists ${had ?? "no"} rows, recomputed lists ${now ?? "no"}`);
    }
  }
  return lines;
}

function main() {
  const computed = computeOverlap();
  if (process.argv.includes("--check")) {
    const committed = existsSync(OVERLAP_PATH) ? JSON.parse(readFileSync(OVERLAP_PATH, "utf8")) : null;
    const current = existsSync(OVERLAP_PATH) ? readFileSync(OVERLAP_PATH, "utf8") : null;
    if (current === serialize(computed)) {
      console.log("eval/routing-qa-overlap.json is current");
      return;
    }
    const lines = overlapDifferences(committed, computed);
    console.error("eval/routing-qa-overlap.json is stale:");
    for (const line of lines.length ? lines : ["rule or layout differs"]) console.error(`  ${line}`);
    console.error(`regenerate with: ${REGENERATE_COMMAND}`);
    process.exit(1);
  }
  writeFileAtomic(OVERLAP_PATH, serialize(computed));
  const counts = Object.entries(computed.sets).map(([name, s]) => `${name} ${s.listed}/${s.total}`);
  console.log(`eval/routing-qa-overlap.json written: ${counts.join(", ")}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
